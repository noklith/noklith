"""Packs pre-rendered frame animations into the iOS asset catalog, losslessly.

Each frame is cropped to the smallest rectangle, centred on the original canvas, that holds every
visible pixel of the whole animation; identical frames are stored once; PNGs are re-saved optimised.
Writes apps/ios/CryptoCardDemo/Assets.xcassets/<Prefix>/ and AnimationClips.swift (play order and canvas).

Usage: python scripts/dev/pack_frame_animations.py Prefix=glob/of/frames/*.png [Prefix=...]
"""
import glob, hashlib, json, os, shutil, sys
from PIL import Image

APP = os.path.join(os.path.dirname(__file__), '..', '..', 'apps', 'ios', 'CryptoCardDemo')
CATALOG = os.path.join(APP, 'Assets.xcassets')
SCALE = 2


def pack(prefix, pattern):
    files = sorted(glob.glob(pattern))
    frames = [Image.open(path).convert('RGBA') for path in files]
    width, height = frames[0].size
    left, top, right, bottom = width, height, 0, 0
    for frame in frames:
        box = frame.getbbox()
        if box:
            left, top, right, bottom = min(left, box[0]), min(top, box[1]), max(right, box[2]), max(bottom, box[3])
    half_w = min(int(max(width / 2 - left, right - width / 2)) + 1, width // 2)
    half_h = min(int(max(height / 2 - top, bottom - height / 2)) + 1, height // 2)
    crop = (width // 2 - half_w, height // 2 - half_h, width // 2 + half_w, height // 2 + half_h)
    folder = os.path.join(CATALOG, prefix)
    shutil.rmtree(folder, ignore_errors=True)
    os.makedirs(folder)
    json.dump({'info': {'author': 'xcode', 'version': 1}}, open(os.path.join(folder, 'Contents.json'), 'w'), indent=2)
    distinct, order = {}, []
    for frame in frames:
        cropped = frame.crop(crop)
        digest = hashlib.sha256(cropped.tobytes()).hexdigest()
        if digest not in distinct:
            distinct[digest] = len(distinct)
            name = f'{prefix}{distinct[digest]:03d}'
            imageset = os.path.join(folder, name + '.imageset')
            os.makedirs(imageset)
            path = os.path.join(imageset, f'{name}@{SCALE}x.png')
            cropped.save(path, optimize=True)
            assert Image.open(path).convert('RGBA').tobytes() == cropped.tobytes(), 'not lossless'
            json.dump({'images': [{'filename': os.path.basename(path), 'idiom': 'universal', 'scale': f'{SCALE}x'}],
                       'info': {'author': 'xcode', 'version': 1}}, open(os.path.join(imageset, 'Contents.json'), 'w'), indent=2)
        order.append(distinct[digest])
    size = (crop[2] - crop[0], crop[3] - crop[1])
    variable = prefix[0].lower() + prefix[1:]
    return (f'    /// {len(frames)} frames, {len(distinct)} distinct; canvas {size[0]}x{size[1]} px of the original {width}x{height} ({SCALE}x).\n'
            f'    static let {variable} = FrameClip(prefix: "{prefix}", order: {order}, '
            f'pixelSize: CGSize(width: {size[0]}, height: {size[1]}), originalPixels: {width}, scale: {SCALE})')


if __name__ == '__main__':
    lines = [pack(*argument.split('=', 1)) for argument in sys.argv[1:]]
    header = ('import CoreGraphics\n\n// Generated by scripts/dev/pack_frame_animations.py: frame order and canvas of each packed animation.\n'
              '// Frames were cropped symmetrically around the centre and duplicates removed; pixels are unchanged.\n\n')
    with open(os.path.join(APP, 'AnimationClips.swift'), 'w', encoding='utf-8', newline='\n') as out:
        out.write(header + 'enum AnimationClips {\n' + '\n'.join(lines) + '\n}\n')
